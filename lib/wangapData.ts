export type WangapBreathEffect = { lavaMax: number; glacierMax: number; per: number };

// 숨결 규칙 — 개수는 2026-08-05 실측·제보 반영:
//   1~5단계(15%) 용숨·빙숨 각 20개(총 40) / 6~15단계(10%·5%) 각 25개(총 50)
//   / 16~25단계(3%·1.5%) 각 30개(총 60).
//   15%·3% 구간은 인게임 실측 확정, 10%·5%·1.5%는 제보 기반.
// 개당 상승폭은 15% 구간 실측(0.375%p)이 "풀숨 = 기본 확률만큼 추가(2배)" 규칙과
// 일치해 전 구간 per = 기본 확률 ÷ total 로 둔다.
// 검산: 풀숨 시 15→30%, 10→20%, 5→10%, 3→6%, 1.5→3%.
const WANGAP_BREATH_TOTALS: { [prob: number]: { total: number; per: number } } = {
  0.15: { total: 40, per: 0.15 / 40 },   // 각 20개 (실측 확정)
  0.10: { total: 50, per: 0.10 / 50 },   // 각 25개
  0.05: { total: 50, per: 0.05 / 50 },   // 각 25개
  0.03: { total: 60, per: 0.03 / 60 },   // 각 30개 (실측 확정 — 15→16강 용숨·빙숨 각 30)
  0.015: { total: 60, per: 0.015 / 60 }, // 각 30개
};

export const getWangapBreathEffect = (baseProb: number): WangapBreathEffect => {
  const t = WANGAP_BREATH_TOTALS[baseProb];
  if (!t) return { lavaMax: 0, glacierMax: 0, per: 0 };
  return { lavaMax: Math.ceil(t.total / 2), glacierMax: Math.floor(t.total / 2), per: t.per };
};

